#!/usr/bin/env python3
"""Generate the NIST ACVP ML-KEM tests from reference/nist-acvp.

Outputs (rewritten in place; --check compares instead), formatted with
`nargo fmt` ($NARGO, else nargo on PATH):
  noir/ml_kem/src/acvp_tests.nr
      Every rank-2/3 case as a Brillig test, plus constrained tests: the
      first keyGen, encapsulation and decapsulation case of each rank, and
      every key-check case. Inputs pass through std::hint::black_box so
      constrained tests execute the ACIR constraints rather than
      constant-folding them.
  noir/lattice_kem_core/src/acvp_decode_tests.nr
      For each rejected encapsulationKeyCheck case, the ek polynomial block
      holding the out-of-range coefficient: non-strict ByteDecode12 accepts it
      and strict ByteDecode12 rejects it. Same input, only the strict range
      check differs, so the KEM-level rejection message is attributed to it.
"""

from pathlib import Path
import argparse
import json
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fixtures import REFERENCE, format_noir as formatted

PROJECT = Path(__file__).resolve().parents[1]
ML_KEM_OUT = PROJECT / "noir/ml_kem/src/acvp_tests.nr"
DECODE_OUT = PROJECT / "noir/lattice_kem_core/src/acvp_decode_tests.nr"
CORE_LIB = PROJECT / "noir/lattice_kem_core/src/lib.nr"
DECODE_MOD = "mod acvp_decode_tests;"

Q = 3329
DK_HASH_MESSAGE = "invalid decapsulation-key hash"
RANGE_MESSAGE = "call to assert_max_bit_size"


def arr(x):
    return str(list(bytes.fromhex(x)))


def bb(x):
    return f"std::hint::black_box({x})"


def coefficients(block):
    """ByteDecode12 without reduction: 256 12-bit integers in [0, 4096)."""
    out = []
    for j in range(128):
        a = block[3 * j] | block[3 * j + 1] << 8 | block[3 * j + 2] << 16
        out += [a & 0xFFF, a >> 12]
    return out


def out_of_range_blocks(ek, rank):
    return [
        i
        for i in range(rank)
        if any(c >= Q for c in coefficients(ek[384 * i : 384 * i + 384]))
    ]


def cases():
    for kind in ["keyGen", "encapDecap"]:
        data = json.loads(
            (REFERENCE / f"nist-acvp/ML-KEM-{kind}-FIPS203.json").read_text()
        )
        for group in data["testGroups"]:
            size = group["parameterSet"].split("-")[-1]
            if size == "1024":
                continue
            rank = 2 if size == "512" else 3
            op = group.get("function", "keygen")
            for index, test in enumerate(group["tests"]):
                yield size, rank, op, index, group, test


def decode_test_name(size, tc_id, strict, brillig):
    kind = "strict_decode_rejects" if strict else "nonstrict_decode_accepts"
    return f"{'brillig' if brillig else 'constrained'}_{kind}_{size}_{tc_id}"


def emit_decode_pair(size, tc, block_index, block):
    reduced = [c % Q for c in coefficients(block)]
    constant = f"EK_{size}_{tc}_BLOCK_{block_index}"
    out = ["", f"global {constant}: [u8; 384] = {list(block)};"]
    for brillig in (False, True):
        modifier = "unconstrained " if brillig else ""
        out.append("#[test]")
        out.append(f"{modifier}fn {decode_test_name(size, tc, False, brillig)}() {{")
        out.append(
            f"    assert(poly::decode::<12>({bb(constant)}, false) == {reduced});"
        )
        out.append("}")
        out.append(f'#[test(should_fail_with = "{RANGE_MESSAGE}")]')
        out.append(f"{modifier}fn {decode_test_name(size, tc, True, brillig)}() {{")
        out.append(f"    let _ = poly::decode::<12>({bb(constant)}, true);")
        out.append("}")
    return out


def build():
    kem = [
        "// Generated by scripts/generate_acvp_tests.py from NIST ACVP final FIPS 203",
        "// vectors; see reference/nist-acvp. Do not edit by hand.",
    ]
    decode = [
        "// Generated by scripts/generate_acvp_tests.py from the rejected NIST ACVP",
        "// encapsulationKeyCheck cases. Do not edit by hand. Each ek block holds a",
        "// coefficient in [3329, 4096): non-strict ByteDecode12 reduces it and strict",
        "// ByteDecode12 rejects it, so only the strict range check can reject the ek.",
        "use crate::poly;",
    ]
    count = constrained = 0
    for size, rank, op, index, group, test in cases():
        count += 1
        tc = test["tcId"]
        name = f"acvp_{size}_{op}_{tc}"
        fail = test.get("testPassed") is False
        attribute, note = "#[test]", None
        body = []
        if op == "keygen":
            body.append(
                f"let (ek, dk) = crate::mlkem{size}::keygen({bb(arr(test['d']))}, {bb(arr(test['z']))});"
            )
            body.append(f"assert(ek == {arr(test['ek'])});")
            body.append(f"assert(dk == {arr(test['dk'])});")
        elif op == "encapsulation":
            body.append(
                f"let (ct, key) = crate::mlkem{size}::encapsulate({bb(arr(test['ek']))}, {bb(arr(test['m']))});"
            )
            body.append(f"assert(ct == {arr(test['c'])});")
            body.append(f"assert(key == {arr(test['k'])});")
        elif op == "decapsulation":
            dk = test.get("dk", group.get("dk"))
            body.append(
                f"assert(crate::mlkem{size}::decapsulate({bb(arr(dk))}, {bb(arr(test['c']))}) == {arr(test['k'])});"
            )
        elif op == "decapsulationKeyCheck":
            # The all-zero ciphertext is a valid decapsulation input, so only
            # the decapsulation-key hash check can reject.
            body.append(
                f"let _ = crate::mlkem{size}::decapsulate({bb(arr(test['dk']))}, {bb(f'[0; {320 * rank + 128}]')});"
            )
            if fail:
                attribute = f'#[test(should_fail_with = "{DK_HASH_MESSAGE}")]'
        elif op == "encapsulationKeyCheck":
            ek = bytes.fromhex(test["ek"])
            blocks = out_of_range_blocks(ek, rank)
            # Cross-check the ACVP verdict against the Section 7.2 condition.
            assert bool(blocks) == fail, (size, tc, blocks)
            body.append(
                f"let _ = crate::mlkem{size}::encapsulate({bb(arr(test['ek']))}, {bb('[0; 32]')});"
            )
            if fail:
                attribute = f'#[test(should_fail_with = "{RANGE_MESSAGE}")]'
                block = blocks[0]
                note = (
                    "// This message is not unique to the strict decoder. The pair\n"
                    f"// lattice_kem_core::acvp_decode_tests::*_decode_*_{size}_{tc}\n"
                    f"// isolates the strict ByteDecode12 check on ek block {block}."
                )
                decode += emit_decode_pair(
                    size, tc, block, ek[384 * block : 384 * block + 384]
                )
        else:
            raise ValueError(op)
        kem.append("")
        kem.append(f"fn case_{size}_{op}_{tc}() {{")
        kem += ["    " + line for line in body]
        kem.append("}")
        for line in [note] if note else []:
            kem.append(line)
        kem.append(attribute)
        kem.append(f"unconstrained fn {name}() {{")
        kem.append(f"    case_{size}_{op}_{tc}();")
        kem.append("}")
        # Constrained runs: the first case of each relation, and every
        # key-check case (accepted and rejected).
        if not (op.endswith("KeyCheck") or index == 0):
            continue
        constrained += 1
        if note:
            kem.append(note)
        kem.append(attribute)
        kem.append(f"fn constrained_{name}() {{")
        kem.append(f"    case_{size}_{op}_{tc}();")
        kem.append("}")
    return (
        "\n".join(kem) + "\n",
        "\n".join(decode) + "\n",
        count,
        constrained,
    )


def core_lib(text):
    lines = text.splitlines()
    if DECODE_MOD not in lines:
        lines.insert(lines.index("mod tests;") + 1, DECODE_MOD)
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check", action="store_true", help="fail if any output differs"
    )
    args = parser.parse_args()
    kem, decode, count, constrained = build()
    kem, decode = formatted([kem, decode])
    outputs = {
        ML_KEM_OUT: kem,
        DECODE_OUT: decode,
        CORE_LIB: core_lib(CORE_LIB.read_text()),
    }
    if args.check:
        stale = [
            p for p, text in outputs.items() if not p.exists() or p.read_text() != text
        ]
        if stale:
            raise SystemExit(
                "stale ACVP tests: "
                + ", ".join(str(p.relative_to(PROJECT)) for p in stale)
            )
        return
    for path, text in outputs.items():
        path.write_text(text)
    print(
        f"Generated {count} official ACVP cases ({constrained} also constrained)"
    )


if __name__ == "__main__":
    main()
