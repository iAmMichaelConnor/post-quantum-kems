#!/usr/bin/env python3
"""A FIPS 203 §7.3 input-domain regression; no reference source is modified."""

from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from fixtures import Outputs

root = Path(__file__).resolve().parents[1]
outputs = Outputs(__doc__)
sys.path.insert(0, str(root / "reference/kyber-py/src"))
from kyber_py.ml_kem import ML_KEM_512, ML_KEM_768

noir = ["// Generated by scripts/generate_decapsulation_alias_cases.py."]
for k, kem in [(2, ML_KEM_512), (3, ML_KEM_768)]:
    # Every encoded t coefficient is q, congruent to zero modulo q.
    pair = 3329 | (3329 << 12)
    pk = pair.to_bytes(3, "little") * (128 * k) + bytes(range(32))
    canonical_pk = bytes(384 * k) + pk[-32:]
    m = bytes([42]) * 32
    z = bytes([73]) * 32
    key, coins = kem._G(m + kem._H(pk))
    # kyber-py adds an encapsulation-only modulus check inside K-PKE.Encrypt.
    # Feed the mathematically equivalent reduced vector to that helper. Hash
    # the original byte string above, exactly as Decaps_internal requires.
    ct = kem._k_pke_encrypt(canonical_pk, m, coins)
    sk = bytes(384 * k) + pk + kem._H(pk) + z
    assert kem._k_pke_decrypt(bytes(384 * k), ct) == m
    assert kem._k_pke_encrypt(canonical_pk, m, coins) == ct
    try:
        kem._decaps_internal(sk, ct)
    except ValueError as e:
        assert "Modulus check" in str(e)
    else:
        raise AssertionError("Expected pinned reference extra modulus check")
    name = "mlkem" + ("512" if k == 2 else "768")
    noir += [
        "#[test]",
        f"unconstrained fn accepts_hash_consistent_alias_key_{k}() {{",
        f" let sk: [u8; {len(sk)}] = {list(sk)};",
        f" let ct: [u8; {len(ct)}] = {list(ct)};",
        f" assert(crate::{name}::decapsulate(sk, ct) == {list(key)});",
        "}",
    ]
outputs.add(root / "noir/ml_kem/src/alias_tests.nr", "\n".join(noir) + "\n")
p = root / "noir/ml_kem/src/lib.nr"
s = p.read_text()
if "mod alias_tests;" not in s:
    s += "\nmod alias_tests;\n"
outputs.add(p, s)
outputs.finish()
