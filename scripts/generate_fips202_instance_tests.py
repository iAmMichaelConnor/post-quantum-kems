#!/usr/bin/env python3
"""Generate noir/fips202/src/instance_tests.nr from Python hashlib.

The tests pin the compile-time FIPS 202 instance guard of the public sponge
APIs. Positive tests run every allowed (rate, suffix)
pair through the byte, lane and word sponges against hashlib. Negative tests
instantiate rejected pairs and expect the static assertion message.

Usage: python3 scripts/generate_fips202_instance_tests.py [--check]
"""

import argparse
import hashlib
import pathlib
import struct
import sys

from fixtures import format_noir as formatted

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "noir/fips202/src/instance_tests.nr"
MESSAGE = "not a FIPS 202 rate and domain suffix"

# (name, rate in bytes, domain suffix, hashlib function, output bytes)
INSTANCES = [
    ("sha3_224", 144, 6, lambda b, n: hashlib.sha3_224(b).digest(), 28),
    ("sha3_256", 136, 6, lambda b, n: hashlib.sha3_256(b).digest(), 32),
    ("sha3_384", 104, 6, lambda b, n: hashlib.sha3_384(b).digest(), 48),
    ("sha3_512", 72, 6, lambda b, n: hashlib.sha3_512(b).digest(), 64),
    ("shake128", 168, 31, lambda b, n: hashlib.shake_128(b).digest(n), 200),
    ("shake256", 136, 31, lambda b, n: hashlib.shake_256(b).digest(n), 200),
]

# Rejected instances: (test name, API, N, output length, R, D, reason).
# The reason is a comment in the generated test.
REJECTED = [
    ("rate_12_byte", "sponge", 9, 16, 12, 31, "rate not lane-aligned"),
    ("rate_4_byte", "sponge", 9, 16, 4, 31, "rate below one lane"),
    ("rate_208_byte", "sponge", 9, 16, 208, 31, "rate above the state"),
    ("rate_128_byte", "sponge", 9, 16, 128, 31, "lane-aligned, not a FIPS 202 rate"),
    ("rate_12_lanes", "sponge_lanes", 12, 2, 12, 31, "rate not lane-aligned"),
    ("rate_12_words", "sponge_words", 1, 2, 12, 6, "rate not lane-aligned"),
    ("suffix_134_byte", "sponge", 135, 32, 136, 134, "0x86 collides with 0x06"),
    ("suffix_134_lanes", "sponge_lanes", 135, 4, 136, 134, "0x86 collides"),
    ("suffix_0_byte", "sponge", 33, 32, 136, 0, "zero suffix drops the domain"),
    ("suffix_0_words", "sponge_words", 4, 4, 136, 0, "zero suffix"),
    ("suffix_7_byte", "sponge", 32, 32, 136, 7, "not a FIPS 202 suffix"),
    ("suffix_262_words", "sponge_words", 4, 4, 136, 262, "262 mod 256 is 6"),
    ("shake_suffix_sha3_512_rate", "sponge", 32, 64, 72, 31, "no SHAKE at rate 72"),
    ("sha3_suffix_shake128_rate", "sponge_lanes", 32, 4, 168, 6, "no SHA3 at rate 168"),
]


def data(n):
    return bytes((7 * i + n) % 256 for i in range(n))


def u8_list(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def u64_list(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def lanes(digest):
    return [
        struct.unpack("<Q", digest[8 * i : 8 * i + 8])[0]
        for i in range(len(digest) // 8)
    ]


def wrap(text, indent):
    """Break a long bracketed list for nargo fmt (max width 100)."""
    pad = " " * indent
    if len(pad) + len(text) <= 100:
        return pad + text
    items = text[1:-1].split(", ")
    lines, line = [], ""
    inner = pad + "    "
    for item in items:
        candidate = (line + " " if line else "") + item + ","
        if len(inner) + len(candidate) > 100:
            lines.append(inner + line)
            line = item + ","
        else:
            line = candidate
    lines.append(inner + line)
    return pad + "[\n" + "\n".join(lines) + "\n" + pad + "]"


def assertion(call, expected):
    one_line = f"    assert({call} == {expected});"
    if len(one_line) <= 100:
        return one_line
    body = wrap(expected, 12).lstrip()
    return f"    assert(\n        {call}\n            == {body},\n    );"


def render():
    out = [
        "// Generated by scripts/generate_fips202_instance_tests.py from Python hashlib.",
        "// Do not edit by hand. Inputs remain witnesses.",
        "",
        "// Every FIPS 202 instance compiles and matches hashlib, including the",
        "// rate-minus-one length where the suffix and the final pad bit share a byte.",
    ]
    for name, rate, suffix, fn, out_len in INSTANCES:
        n = rate - 1
        o = 32 if out_len == 200 else out_len
        digest = fn(data(n), o)
        out += [
            "#[test]",
            f"fn {name}_bytes_{n}() {{",
            f"    let input: [u8; {n}] = std::hint::black_box(data::<{n}>());",
            assertion(
                f"crate::sponge::<{n}, {o}, {rate}, {suffix}>(input)", u8_list(digest)
            ),
            "}",
        ]
        # Lane API: a full rate block of input adds a second padding block.
        n = rate
        count = (32 if out_len == 200 else out_len) // 8
        digest = fn(data(n), 8 * count)
        out += [
            "#[test]",
            f"fn {name}_lanes_{n}() {{",
            f"    let input: [u8; {n}] = std::hint::black_box(data::<{n}>());",
            assertion(
                f"crate::sponge_lanes::<{n}, {count}, {rate}, {suffix}>(input)",
                u64_list(lanes(digest)),
            ),
            "}",
        ]
        # Word API: a full rate block of words.
        words = rate // 8
        digest = fn(data(8 * words), 8 * count)
        out += [
            "#[test]",
            f"fn {name}_words_{words}() {{",
            f"    let input: [u64; {words}] = std::hint::black_box(words::<{words}>());",
            assertion(
                f"crate::sponge_words::<{words}, {count}, {rate}, {suffix}>(input)",
                u64_list(lanes(digest)),
            ),
            "}",
        ]
    out += [
        "",
        "// Rejected instances fail at compile time in the constraint system build.",
        "// A runtime (witness) suffix or rate cannot be written: both are generics.",
    ]
    for name, api, n, o, rate, suffix, reason in REJECTED:
        if api == "sponge_words":
            arg = f"words::<{n}>()"
        else:
            arg = f"data::<{n}>()"
        out += [
            "// " + reason,
            f'#[test(should_fail_with = "{MESSAGE}")]',
            f"fn rejects_{name}() {{",
            f"    let _ = crate::{api}::<{n}, {o}, {rate}, {suffix}>(std::hint::black_box({arg}));",
            "}",
        ]
    out += [
        "",
        "// Test input: byte i is (7 * i + N) mod 256, as in the generator.",
        "fn data<let N: u32>() -> [u8; N] {",
        "    let mut out = [0u8; N];",
        "    for i in 0..N {",
        "        out[i] = ((7 * i + N) % 256) as u8;",
        "    }",
        "    out",
        "}",
        "",
        "// The same bytes as little-endian 64-bit words.",
        "fn words<let W: u32>() -> [u64; W] {",
        "    let bytes = data::<8 * W>();",
        "    let mut out = [0u64; W];",
        "    for i in 0..W {",
        "        for j in 0..8 {",
        "            out[i] += (bytes[8 * i + j] as u64) << (8 * j) as u64;",
        "        }",
        "    }",
        "    out",
        "}",
    ]
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the file is stale"
    )
    args = parser.parse_args()
    (text,) = formatted([render()])
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f"stale: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
